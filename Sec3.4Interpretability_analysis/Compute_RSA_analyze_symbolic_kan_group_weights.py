def ensure_dir(path: str) -> str:
    os.makedirs(path, exist_ok=True)
    return path


def parse_int_list(s: str) -> List[int]:
    return [int(x.strip()) for x in s.split(",") if x.strip()]


def parse_str_list(s: str) -> List[str]:
    return [x.strip() for x in s.split(",") if x.strip()]


def sanitize_name(name: Any) -> str:
    name = str(name)
    name = re.sub(r"[^a-zA-Z0-9_\-\.]+", "_", name)
    return name.strip("_") or "unknown"


def layer_name_to_index(layer_name: Any) -> int:
    """Convert 'Layer1' to 0, 'Layer2' to 1, etc."""
    s = str(layer_name)
    nums = re.findall(r"\d+", s)
    if not nums:
        raise ValueError(f"Cannot parse layer index from layer name: {layer_name}")
    return int(nums[-1]) - 1


def index_to_layer_name(layer_idx: int) -> str:
    return f"Layer{layer_idx + 1}"


def load_checkpoint_state(checkpoint: Any, preferred_key: str = "parameter") -> Dict[str, torch.Tensor]:
    """Load model state dict from different possible checkpoint formats."""
    if isinstance(checkpoint, dict):
        candidate_keys = [preferred_key, "parameter", "state_dict", "model_state_dict", "net", "model"]
        for key in candidate_keys:
            if key in checkpoint and isinstance(checkpoint[key], dict):
                return checkpoint[key]

        # Some checkpoints are already plain state dicts.
        if all(isinstance(k, str) for k in checkpoint.keys()):
            tensor_like = [torch.is_tensor(v) for v in checkpoint.values()]
            if len(tensor_like) > 0 and sum(tensor_like) / len(tensor_like) > 0.5:
                return checkpoint

    raise ValueError(
        "Cannot find a valid state_dict in checkpoint. "
        "Try setting --checkpoint_key to the correct key."
    )


def load_symbolic_kan_model(args, device: str) -> SymbolicKAN:
    layers_hidden = parse_int_list(args.layers_hidden)
    elementary_functions = parse_str_list(args.elementary_functions)

    unknown = [f for f in elementary_functions if f not in SUPPORTED_ELEMENTARY_FUNCTIONS]
    if unknown:
        raise ValueError(f"Unsupported elementary function(s): {unknown}")

    if args.base_activation not in BASE_ACTIVATION_MAP:
        raise ValueError(f"Unsupported base activation: {args.base_activation}")

    net = SymbolicKAN(
        layers_hidden=layers_hidden,
        scale_base=args.scale_base,
        scale_mlp=args.scale_mlp,
        base_activation=BASE_ACTIVATION_MAP[args.base_activation],
        elementary_functions=elementary_functions,
    ).to(device)

    checkpoint = torch.load(args.model_path, map_location=device)
    state_dict = load_checkpoint_state(checkpoint, preferred_key=args.checkpoint_key)

    # Remove possible 'module.' prefix from DataParallel checkpoints.
    cleaned_state_dict = {}
    for k, v in state_dict.items():
        new_k = k.replace("module.", "", 1) if k.startswith("module.") else k
        cleaned_state_dict[new_k] = v

    missing, unexpected = net.load_state_dict(cleaned_state_dict, strict=False)
    if missing:
        print("[Warning] Missing keys when loading checkpoint:", missing)
    if unexpected:
        print("[Warning] Unexpected keys when loading checkpoint:", unexpected)

    net.eval()
    return net


def resolve_class_csv(args) -> str:
    if args.class_csv:
        if not os.path.isfile(args.class_csv):
            raise FileNotFoundError(f"--class_csv does not exist: {args.class_csv}")
        return args.class_csv

    # Try to find the common outputs of Compute_RSA_neuron(30).py.
    candidates = [
        os.path.join(args.rsa_save_dir, f"neuron_level_rsa_results_r_ge_{args.r_threshold}.csv"),
        os.path.join(args.rsa_save_dir, "neuron_level_rsa_results.csv"),
    ]
    for p in candidates:
        if os.path.isfile(p):
            return p

    raise FileNotFoundError(
        "Cannot find classification CSV. Please pass --class_csv explicitly. Tried:\n" +
        "\n".join(candidates)
    )


def load_classification_df(args) -> pd.DataFrame:
    class_csv = resolve_class_csv(args)
    df = pd.read_csv(class_csv)

    required = {"layer", "neuron", args.class_col}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Classification CSV lacks required column(s): {missing}")

    df = df.copy()
    df["neuron"] = df["neuron"].astype(int)
    df["layer_idx"] = df["layer"].apply(layer_name_to_index).astype(int)
    df["class_label"] = df[args.class_col].astype(str)

    if args.r_threshold is not None and "best_r" in df.columns:
        df = df[df["best_r"] >= args.r_threshold].copy()

    if args.p_threshold is not None and "best_p" in df.columns:
        df = df[df["best_p"] <= args.p_threshold].copy()

    if args.layers:
        keep_layers = set(parse_str_list(args.layers))
        df = df[df["layer"].astype(str).isin(keep_layers)].copy()

    if len(df) == 0:
        raise ValueError(
            "No neurons remain after filtering. Try lowering --r_threshold, "
            "removing --p_threshold, or checking --class_csv."
        )

    return df


def to_numpy(x: torch.Tensor) -> np.ndarray:
    return x.detach().cpu().numpy()


@dataclass
class LayerParams:
    layer_idx: int
    layer_name: str
    in_features: int
    out_features: int
    elementary_functions: List[str]
    scale_mlp: float
    base_weight: np.ndarray       # [out, in]
    C: np.ndarray                 # [M, out, in]
    D: np.ndarray                 # [M, out]
    ef_weights: np.ndarray        # [M]


def extract_layer_params(layer: SymbolicKANLinear, layer_idx: int) -> LayerParams:
    C = np.stack([to_numpy(p) for p in layer.ef_mlp_linears], axis=0)
    D = np.stack([to_numpy(p) for p in layer.ef_mlp_biases], axis=0)
    return LayerParams(
        layer_idx=layer_idx,
        layer_name=index_to_layer_name(layer_idx),
        in_features=layer.in_features,
        out_features=layer.out_features,
        elementary_functions=list(layer.elementary_functions),
        scale_mlp=float(layer.scale_mlp),
        base_weight=to_numpy(layer.base_weight),
        C=C,
        D=D,
        ef_weights=to_numpy(layer.ef_weights),
    )


def build_all_node_param_vectors(
    params: LayerParams,
    scale_param_vector: bool = True,
    include_ef_weight: bool = False,
    include_bias: bool = True,
    include_base: bool = True,
) -> np.ndarray:
    """
    Build parameter vector theta_{l,i} for every output neuron in one layer.

    By default, the elementary-function branch uses scale_mlp * c_{m,l,i,j}
    and scale_mlp * d_{l,m,i}, but it does NOT multiply by the elementary
    function prefactor w_{l,m}. This keeps the feature vector independent of
    the layer-shared elementary-function weight.

    Set include_ef_weight=True only if you want the old behavior:
    scale_mlp * w_{l,m} * c_{m,l,i,j} and scale_mlp * w_{l,m} * d_{l,m,i}.
    Set scale_param_vector=False to use raw C and D.
    """
    M, O, I = params.C.shape
    parts = []

    C = params.C.copy()
    D = params.D.copy()
    if scale_param_vector:
        ef_scale = np.full(M, params.scale_mlp, dtype=np.float64)
        if include_ef_weight:
            ef_scale = ef_scale * params.ef_weights.astype(np.float64)
        C = C * ef_scale[:, None, None]
        D = D * ef_scale[:, None]

    # [M, O, I] -> [O, M, I] -> [O, M*I]
    parts.append(np.transpose(C, (1, 0, 2)).reshape(O, M * I))

    if include_bias:
        # [M, O] -> [O, M]
        parts.append(D.T)

    if include_base:
        parts.append(params.base_weight.copy())

    return np.concatenate(parts, axis=1).astype(np.float64)


def zscore_by_reference(X: np.ndarray, reference: np.ndarray, eps: float = 1e-12) -> np.ndarray:
    mu = reference.mean(axis=0, keepdims=True)
    sd = reference.std(axis=0, keepdims=True)
    return (X - mu) / (sd + eps)


def safe_pdist_stats(X: np.ndarray) -> Dict[str, float]:
    n = X.shape[0]
    if n == 0:
        return {
            "mean_l2_to_centroid": np.nan,
            "pairwise_l2_mean": np.nan,
            "pairwise_l2_std": np.nan,
            "pairwise_cosine_mean": np.nan,
            "pairwise_cosine_std": np.nan,
            "param_var_mean": np.nan,
        }

    centroid = X.mean(axis=0, keepdims=True)
    l2_to_centroid = np.linalg.norm(X - centroid, axis=1)

    result = {
        "mean_l2_to_centroid": float(np.mean(l2_to_centroid)),
        "param_var_mean": float(np.mean(np.var(X, axis=0))),
    }

    if n < 2:
        result.update({
            "pairwise_l2_mean": 0.0,
            "pairwise_l2_std": 0.0,
            "pairwise_cosine_mean": 1.0,
            "pairwise_cosine_std": 0.0,
        })
        return result

    d = pdist(X, metric="euclidean")
    result["pairwise_l2_mean"] = float(np.mean(d))
    result["pairwise_l2_std"] = float(np.std(d))

    norms = np.linalg.norm(X, axis=1, keepdims=True)
    Xn = X / (norms + 1e-12)
    sim = Xn @ Xn.T
    upper = sim[np.triu_indices(n, k=1)]
    result["pairwise_cosine_mean"] = float(np.mean(upper))
    result["pairwise_cosine_std"] = float(np.std(upper))
    return result


def mean_pairwise_corr_columns(A: np.ndarray, max_neurons: Optional[int] = None, seed: int = 0) -> Dict[str, float]:
    """Mean pairwise Pearson correlation among neuron activations in columns."""
    if A.ndim != 2:
        raise ValueError("A must be [N_samples, N_neurons]")
    n_neurons = A.shape[1]
    if n_neurons < 2:
        return {"functional_corr_mean": 1.0, "functional_corr_std": 0.0}

    if max_neurons is not None and n_neurons > max_neurons:
        rng = np.random.default_rng(seed)
        keep = rng.choice(n_neurons, size=max_neurons, replace=False)
        A = A[:, keep]
        n_neurons = A.shape[1]

    std = A.std(axis=0)
    valid = std > 1e-12
    A = A[:, valid]
    n_neurons = A.shape[1]
    if n_neurons < 2:
        return {"functional_corr_mean": np.nan, "functional_corr_std": np.nan}

    corr = np.corrcoef(A, rowvar=False)
    upper = corr[np.triu_indices(n_neurons, k=1)]
    upper = upper[np.isfinite(upper)]
    if len(upper) == 0:
        return {"functional_corr_mean": np.nan, "functional_corr_std": np.nan}

    return {
        "functional_corr_mean": float(np.mean(upper)),
        "functional_corr_std": float(np.std(upper)),
    }


