def compute_data_contribution_for_group(
    layer: SymbolicKANLinear,
    params: LayerParams,
    nodes: np.ndarray,
    x_prev_np: np.ndarray,
    h_out_np: Optional[np.ndarray],
    layer_name: str,
    class_label: str,
    device: str,
) -> Tuple[Dict[str, Any], pd.DataFrame, pd.DataFrame]:
    """
    Estimate actual contribution on data.

    Returns:
      summary_row:
        actual elementary-function output magnitude and base output magnitude
      input_df:
        data-weighted input importance per input dimension
      ef_df:
        actual contribution per elementary function
    """
    nodes_t = torch.as_tensor(nodes, dtype=torch.long, device=device)
    x_prev = torch.from_numpy(x_prev_np).float().to(device)

    with torch.no_grad():
        base_act = layer.base_activation(x_prev)                  # [N, I]
        x_abs_mean = torch.mean(torch.abs(x_prev), dim=0)          # [I]
        base_act_abs_mean = torch.mean(torch.abs(base_act), dim=0) # [I]

        base_weight_sel = layer.base_weight.index_select(0, nodes_t)  # [K, I]
        base_output = F.linear(base_act, base_weight_sel)             # [N, K]
        base_output_mean_abs = torch.mean(torch.abs(base_output)).item()

        base_input_importance = (
            torch.mean(torch.abs(base_weight_sel), dim=0) * base_act_abs_mean
        )  # [I]

        ef_rows = []
        ef_input_total = torch.zeros(params.in_features, device=device)
        ef_output_abs_values = []

        for m, fname in enumerate(params.elementary_functions):
            C_m_sel = layer.ef_mlp_linears[m].index_select(0, nodes_t)  # [K, I]
            D_m_sel = layer.ef_mlp_biases[m].index_select(0, nodes_t)   # [K]
            ef_weight_m = layer.ef_weights[m]

            z = F.linear(x_prev, C_m_sel, D_m_sel)                     # [N, K]
            y = SUPPORTED_ELEMENTARY_FUNCTIONS[fname](z) * ef_weight_m * layer.scale_mlp

            y_abs_mean = torch.mean(torch.abs(y)).item()
            y_mean = torch.mean(y).item()
            y_std = torch.std(y).item()
            ef_output_abs_values.append(y_abs_mean)

            # Data-weighted approximate input importance of elementary branch:
            # |scale_mlp * w_m| * mean_i |c_mij| * mean_n |h_{l-1,j}|
            ef_input_m = (
                torch.abs(ef_weight_m * layer.scale_mlp)
                * torch.mean(torch.abs(C_m_sel), dim=0)
                * x_abs_mean
            )
            ef_input_total += ef_input_m

            ef_rows.append({
                "layer": layer_name,
                "class_label": class_label,
                "n_nodes": int(len(nodes)),
                "ef_index": int(m),
                "ef_name": fname,
                "ef_weight": float(ef_weight_m.detach().cpu()),
                "mean_abs_actual_output": float(y_abs_mean),
                "mean_actual_output": float(y_mean),
                "std_actual_output": float(y_std),
                "data_weighted_input_importance_sum": float(torch.sum(ef_input_m).detach().cpu()),
                "data_weighted_input_importance_mean": float(torch.mean(ef_input_m).detach().cpu()),
            })

        ef_total_output_mean_abs_sum = float(np.sum(ef_output_abs_values))

        input_total = ef_input_total + base_input_importance
        input_rows = []
        for j in range(params.in_features):
            input_rows.append({
                "layer": layer_name,
                "class_label": class_label,
                "n_nodes": int(len(nodes)),
                "input_index": int(j),
                "importance_total_data_weighted": float(input_total[j].detach().cpu()),
                "importance_ef_data_weighted": float(ef_input_total[j].detach().cpu()),
                "importance_base_data_weighted": float(base_input_importance[j].detach().cpu()),
                "mean_abs_input": float(x_abs_mean[j].detach().cpu()),
                "mean_abs_base_activation_input": float(base_act_abs_mean[j].detach().cpu()),
            })

        functional_stats = {"functional_corr_mean": np.nan, "functional_corr_std": np.nan}
        if h_out_np is not None:
            h_group = h_out_np[:, nodes]
            functional_stats = mean_pairwise_corr_columns(h_group, max_neurons=300)

        summary_row = {
            "layer": layer_name,
            "class_label": class_label,
            "n_nodes": int(len(nodes)),
            "n_samples": int(x_prev_np.shape[0]),
            "base_output_mean_abs": float(base_output_mean_abs),
            "ef_output_mean_abs_sum": float(ef_total_output_mean_abs_sum),
            "ef_to_base_abs_ratio": float(ef_total_output_mean_abs_sum / (base_output_mean_abs + 1e-12)),
            "top_ef_by_actual_output": str(ef_rows[int(np.argmax(ef_output_abs_values))]["ef_name"]),
            "top_ef_actual_output": float(np.max(ef_output_abs_values)),
            **functional_stats,
        }

    return summary_row, pd.DataFrame(input_rows), pd.DataFrame(ef_rows)


