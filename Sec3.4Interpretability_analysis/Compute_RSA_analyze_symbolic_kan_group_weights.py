"""
Analyze same-layer same-class neurons after Neuron-level RSA classification.

This script is designed for the SymbolicKAN model structure used in
Compute_RSA_neuron(30).py. It reads a trained SymbolicKAN checkpoint and the
neuron classification CSV generated by the RSA script, then analyzes grouped
neurons by layer and class label.

It produces:
  1. class_summary.csv
     - class size, RSA score statistics
     - intra-class parameter consistency
     - mean distance to class centroid
     - pairwise distance / cosine similarity
     - optional data-driven functional similarity

  2. ef_param_stats.csv
     - elementary-function parameter strength per class
     - |c|, |w_m c|, |d|, |w_m d| statistics

  3. input_importance_parameter.csv
     - parameter-based input importance I_{l,k,j}

  4. input_importance_data.csv
     - data-weighted input importance, if test data are available

  5. data_contribution_summary.csv
     - actual elementary-function output contribution and base term contribution
       estimated on sampled test data

  6. inter_class_distance.csv
     - centroid distance between classes within the same layer

  7. npz files under class_mean_params/
     - class-wise mean/variance tensors for C, D, base_weight

  8. figures under figures/
     - class centroid-distance heatmaps
     - top input-importance plots
     - elementary-function contribution plots

Typical usage:

python analyze_symbolic_kan_group_weights.py \
  --model_path /path/to/Last_SymbolicKAN_Para_Silu_1_fold_4L_-524-524-524_15_2.pt \
  --class_csv /path/to/neuron_level_rsa_results_r_ge_0.1.csv \
  --data_root /media/aiofm/F/20250723_k-fold-cross-validation-KAN/1-fold \
  --save_dir /path/to/group_weight_analysis

If you only want parameter-space analysis and do not want to load the dataset:

python analyze_symbolic_kan_group_weights.py \
  --model_path /path/to/model.pt \
  --class_csv /path/to/neuron_level_rsa_results_r_ge_0.1.csv \
  --save_dir /path/to/group_weight_analysis \
  --no_dataset_contribution
"""

