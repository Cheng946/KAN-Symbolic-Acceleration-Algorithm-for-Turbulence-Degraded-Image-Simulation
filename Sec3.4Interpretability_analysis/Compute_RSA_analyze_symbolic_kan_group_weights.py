def compute_class_mean_param_tensors(params: LayerParams, nodes: np.ndarray) -> Dict[str, np.ndarray]:
    C_sel = params.C[:, nodes, :]            # [M, K, I]
    D_sel = params.D[:, nodes]               # [M, K]
    B_sel = params.base_weight[nodes, :]     # [K, I]

    ef_scale = params.scale_mlp * params.ef_weights.astype(np.float64)
    weighted_C = C_sel * ef_scale[:, None, None]
    weighted_D = D_sel * ef_scale[:, None]

    return {
        "nodes": nodes.astype(np.int64),
        "C_mean": C_sel.mean(axis=1),
        "C_var": C_sel.var(axis=1),
        "D_mean": D_sel.mean(axis=1),
        "D_var": D_sel.var(axis=1),
        "weighted_C_mean": weighted_C.mean(axis=1),
        "weighted_C_var": weighted_C.var(axis=1),
        "weighted_D_mean": weighted_D.mean(axis=1),
        "weighted_D_var": weighted_D.var(axis=1),
        "base_weight_mean": B_sel.mean(axis=0),
        "base_weight_var": B_sel.var(axis=0),
        "ef_weights": params.ef_weights.copy(),
    }


def compute_ef_param_stats(params: LayerParams, nodes: np.ndarray, layer_name: str, class_label: str) -> List[Dict[str, Any]]:
    rows = []
    C_sel = params.C[:, nodes, :]
    D_sel = params.D[:, nodes]
    ef_scale = params.scale_mlp * params.ef_weights.astype(np.float64)

    for m, fname in enumerate(params.elementary_functions):
        C_m = C_sel[m]
        D_m = D_sel[m]
        weighted_C_m = C_m * ef_scale[m]
        weighted_D_m = D_m * ef_scale[m]
        rows.append({
            "layer": layer_name,
            "class_label": class_label,
            "n_nodes": int(len(nodes)),
            "ef_index": int(m),
            "ef_name": fname,
            "ef_weight": float(params.ef_weights[m]),
            "scale_mlp": float(params.scale_mlp),
            "mean_abs_c": float(np.mean(np.abs(C_m))),
            "std_abs_c": float(np.std(np.abs(C_m))),
            "mean_abs_weighted_c": float(np.mean(np.abs(weighted_C_m))),
            "std_abs_weighted_c": float(np.std(np.abs(weighted_C_m))),
            "mean_abs_d": float(np.mean(np.abs(D_m))),
            "std_abs_d": float(np.std(np.abs(D_m))),
            "mean_abs_weighted_d": float(np.mean(np.abs(weighted_D_m))),
            "std_abs_weighted_d": float(np.std(np.abs(weighted_D_m))),
            "var_weighted_c_mean": float(np.mean(np.var(weighted_C_m, axis=0))),
            "var_weighted_d": float(np.var(weighted_D_m)),
        })
    return rows


def compute_parameter_input_importance(
    params: LayerParams,
    nodes: np.ndarray,
    layer_name: str,
    class_label: str,
) -> pd.DataFrame:
    """
    Parameter-space input importance:

    I_{l,k,j} = sum_m |scale_mlp * w_{l,m}| mean_i |c_{m,l,i,j}|
                + mean_i |w^b_{l,i,j}|

    This is the direct implementation of the parameter-based index discussed
    in the analysis text.
    """
    C_sel = params.C[:, nodes, :]            # [M, K, I]
    B_sel = params.base_weight[nodes, :]     # [K, I]

    ef_scale_abs = np.abs(params.scale_mlp * params.ef_weights.astype(np.float64))
    ef_part_by_m = ef_scale_abs[:, None] * np.mean(np.abs(C_sel), axis=1)  # [M, I]
    ef_part_total = ef_part_by_m.sum(axis=0)                               # [I]
    base_part = np.mean(np.abs(B_sel), axis=0)                             # [I]
    total = ef_part_total + base_part

    rows = []
    for j in range(params.in_features):
        row = {
            "layer": layer_name,
            "class_label": class_label,
            "n_nodes": int(len(nodes)),
            "input_index": int(j),
            "importance_total": float(total[j]),
            "importance_ef_total": float(ef_part_total[j]),
            "importance_base": float(base_part[j]),
        }
        for m, fname in enumerate(params.elementary_functions):
            row[f"importance_ef_{m}_{fname}"] = float(ef_part_by_m[m, j])
        rows.append(row)
    return pd.DataFrame(rows)


