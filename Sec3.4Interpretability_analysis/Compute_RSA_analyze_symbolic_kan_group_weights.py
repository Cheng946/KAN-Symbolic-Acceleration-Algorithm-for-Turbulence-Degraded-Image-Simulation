def plot_inter_class_heatmap(layer_name: str, labels: List[str], mat: np.ndarray, save_path: str):
    if len(labels) == 0:
        return
    fig_w = max(6, 0.55 * len(labels) + 3)
    fig_h = max(5, 0.50 * len(labels) + 2)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    im = ax.imshow(mat, cmap="viridis")
    ax.set_xticks(np.arange(len(labels)))
    ax.set_yticks(np.arange(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.set_yticklabels(labels)
    ax.set_title(f"{layer_name}: inter-class centroid distance")
    ax.set_xlabel("Class label")
    ax.set_ylabel("Class label")
    for i in range(len(labels)):
        for j in range(len(labels)):
            ax.text(j, i, f"{mat[i, j]:.2f}", ha="center", va="center", fontsize=8)
    fig.colorbar(im, ax=ax, label="Euclidean distance")
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


