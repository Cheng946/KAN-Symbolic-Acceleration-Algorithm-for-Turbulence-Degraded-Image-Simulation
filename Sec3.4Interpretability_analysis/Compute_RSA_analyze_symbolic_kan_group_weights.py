def _safe_class_mean_var(x: np.ndarray, class_axis: int, eps: float = 1e-12) -> Tuple[np.ndarray, np.ndarray]:
    """Mean and variance along the class/neuron axis with float64 precision."""
    x = np.asarray(x, dtype=np.float64)
    if x.shape[class_axis] == 0:
        raise ValueError("Cannot compute class statistics for an empty class.")
    return np.mean(x, axis=class_axis), np.var(x, axis=class_axis) + eps


def _standardized_difference(mu_a: np.ndarray, mu_b: np.ndarray, var_a: np.ndarray, var_b: np.ndarray, eps: float = 1e-12) -> np.ndarray:
    """
    Cohen-d-like standardized mean difference for parameter dimensions.

    z_q = (mu_a_q - mu_b_q) / sqrt(0.5 * (var_a_q + var_b_q) + eps)

    This helps distinguish a large raw difference from a difference that is
    large relative to within-class dispersion.
    """
    return (mu_a - mu_b) / np.sqrt(0.5 * (var_a + var_b) + eps)


def _array_l2_stats(diff: np.ndarray, z: np.ndarray) -> Dict[str, float]:
    diff = np.asarray(diff, dtype=np.float64)
    z = np.asarray(z, dtype=np.float64)
    raw_sq = float(np.sum(diff ** 2))
    z_sq = float(np.sum(z ** 2))
    n_dim = int(diff.size)
    return {
        "n_dimensions": n_dim,
        "raw_l2": float(np.sqrt(raw_sq)),
        "raw_l2_sq": raw_sq,
        "raw_rms_diff": float(np.sqrt(raw_sq / max(n_dim, 1))),
        "raw_mean_abs_diff": float(np.mean(np.abs(diff))) if n_dim > 0 else np.nan,
        "standardized_l2": float(np.sqrt(z_sq)),
        "standardized_l2_sq": z_sq,
        "standardized_rms_diff": float(np.sqrt(z_sq / max(n_dim, 1))),
        "standardized_mean_abs_diff": float(np.mean(np.abs(z))) if n_dim > 0 else np.nan,
    }


def compute_inter_class_parameter_differences(
    params: LayerParams,
    nodes_a: np.ndarray,
    nodes_b: np.ndarray,
    layer_name: str,
    class_a: str,
    class_b: str,
    include_ef_weight: bool = True,
    top_dims: int = 30,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]], List[Dict[str, Any]], List[Dict[str, Any]], Dict[str, Any]]:
    """
    Decompose same-layer inter-class parameter differences.

    The previous inter_class_distance.csv only reports centroid distance. This
    function explains what produces that distance by decomposing class-pair
    differences into:
      1) parameter blocks: each elementary-function C branch, each D bias, base_weight;
      2) elementary functions: C_m + D_m for each elementary function;
      3) input dimensions: all C_{m,j} plus base_weight_j;
      4) individual parameter dimensions with the largest standardized effect.

    Raw differences answer "where is the centroid distance large?".
    Standardized differences answer "where is the difference large relative to
    within-class variability?".
    """
    nodes_a = np.asarray(nodes_a, dtype=np.int64)
    nodes_b = np.asarray(nodes_b, dtype=np.int64)
    M, O, I = params.C.shape

    C_a = params.C[:, nodes_a, :]              # [M, Ka, I]
    C_b = params.C[:, nodes_b, :]              # [M, Kb, I]
    D_a = params.D[:, nodes_a]                 # [M, Ka]
    D_b = params.D[:, nodes_b]                 # [M, Kb]
    B_a = params.base_weight[nodes_a, :]       # [Ka, I]
    B_b = params.base_weight[nodes_b, :]       # [Kb, I]

    C_mu_a, C_var_a = _safe_class_mean_var(C_a, class_axis=1)
    C_mu_b, C_var_b = _safe_class_mean_var(C_b, class_axis=1)
    D_mu_a, D_var_a = _safe_class_mean_var(D_a, class_axis=1)
    D_mu_b, D_var_b = _safe_class_mean_var(D_b, class_axis=1)
    B_mu_a, B_var_a = _safe_class_mean_var(B_a, class_axis=0)
    B_mu_b, B_var_b = _safe_class_mean_var(B_b, class_axis=0)

    # Use effective branch scaling by default because it reflects the actual
    # layer computation. ef_weights are shared within a layer, so they do not
    # themselves create class differences, but they do change the relative
    # contribution of each elementary-function branch to the output.
    if include_ef_weight:
        ef_scale = params.scale_mlp * params.ef_weights.astype(np.float64)
    else:
        ef_scale = np.full(M, params.scale_mlp, dtype=np.float64)

    C_mu_a_eff = C_mu_a * ef_scale[:, None]
    C_mu_b_eff = C_mu_b * ef_scale[:, None]
    C_var_a_eff = C_var_a * (ef_scale[:, None] ** 2)
    C_var_b_eff = C_var_b * (ef_scale[:, None] ** 2)
    D_mu_a_eff = D_mu_a * ef_scale
    D_mu_b_eff = D_mu_b * ef_scale
    D_var_a_eff = D_var_a * (ef_scale ** 2)
    D_var_b_eff = D_var_b * (ef_scale ** 2)

    dC = C_mu_a_eff - C_mu_b_eff               # [M, I]
    dD = D_mu_a_eff - D_mu_b_eff               # [M]
    dB = B_mu_a - B_mu_b                       # [I]
    zC = _standardized_difference(C_mu_a_eff, C_mu_b_eff, C_var_a_eff, C_var_b_eff)
    zD = _standardized_difference(D_mu_a_eff, D_mu_b_eff, D_var_a_eff, D_var_b_eff)
    zB = _standardized_difference(B_mu_a, B_mu_b, B_var_a, B_var_b)

    total_raw_sq = float(np.sum(dC ** 2) + np.sum(dD ** 2) + np.sum(dB ** 2))
    total_z_sq = float(np.sum(zC ** 2) + np.sum(zD ** 2) + np.sum(zB ** 2))
    eps = 1e-12

    block_rows: List[Dict[str, Any]] = []

    def add_block(block_name: str, block_type: str, diff: np.ndarray, z: np.ndarray, ef_index: Optional[int] = None, ef_name: str = ""):
        st = _array_l2_stats(diff, z)
        row = {
            "layer": layer_name,
            "class_label_a": str(class_a),
            "class_label_b": str(class_b),
            "n_nodes_a": int(len(nodes_a)),
            "n_nodes_b": int(len(nodes_b)),
            "block": block_name,
            "block_type": block_type,
            "ef_index": np.nan if ef_index is None else int(ef_index),
            "ef_name": ef_name,
            "include_ef_weight": bool(include_ef_weight),
            **st,
        }
        row["raw_contribution_ratio"] = float(st["raw_l2_sq"] / (total_raw_sq + eps))
        row["standardized_contribution_ratio"] = float(st["standardized_l2_sq"] / (total_z_sq + eps))
        block_rows.append(row)

    for m, fname in enumerate(params.elementary_functions):
        add_block(f"{fname}_C", "elementary_C", dC[m], zC[m], ef_index=m, ef_name=fname)
        add_block(f"{fname}_D", "elementary_D", np.asarray([dD[m]]), np.asarray([zD[m]]), ef_index=m, ef_name=fname)
    add_block("base_weight", "base_weight", dB, zB, ef_index=None, ef_name="base")

    ef_rows: List[Dict[str, Any]] = []
    ef_raw_scores = np.sum(dC ** 2, axis=1) + dD ** 2
    ef_z_scores = np.sum(zC ** 2, axis=1) + zD ** 2
    ef_raw_total = float(np.sum(ef_raw_scores))
    ef_z_total = float(np.sum(ef_z_scores))
    for m, fname in enumerate(params.elementary_functions):
        ef_rows.append({
            "layer": layer_name,
            "class_label_a": str(class_a),
            "class_label_b": str(class_b),
            "n_nodes_a": int(len(nodes_a)),
            "n_nodes_b": int(len(nodes_b)),
            "ef_index": int(m),
            "ef_name": fname,
            "ef_scale_used": float(ef_scale[m]),
            "C_raw_l2_sq": float(np.sum(dC[m] ** 2)),
            "D_raw_l2_sq": float(dD[m] ** 2),
            "ef_raw_l2_sq": float(ef_raw_scores[m]),
            "ef_raw_l2": float(np.sqrt(ef_raw_scores[m])),
            "ef_raw_contribution_ratio_among_ef": float(ef_raw_scores[m] / (ef_raw_total + eps)),
            "ef_raw_contribution_ratio_total": float(ef_raw_scores[m] / (total_raw_sq + eps)),
            "C_standardized_l2_sq": float(np.sum(zC[m] ** 2)),
            "D_standardized_l2_sq": float(zD[m] ** 2),
            "ef_standardized_l2_sq": float(ef_z_scores[m]),
            "ef_standardized_l2": float(np.sqrt(ef_z_scores[m])),
            "ef_standardized_contribution_ratio_among_ef": float(ef_z_scores[m] / (ef_z_total + eps)),
            "ef_standardized_contribution_ratio_total": float(ef_z_scores[m] / (total_z_sq + eps)),
            "mean_abs_C_diff": float(np.mean(np.abs(dC[m]))),
            "mean_abs_C_standardized_diff": float(np.mean(np.abs(zC[m]))),
            "D_diff": float(dD[m]),
            "D_standardized_diff": float(zD[m]),
        })

    input_rows: List[Dict[str, Any]] = []
    input_raw_scores = np.sum(dC ** 2, axis=0) + dB ** 2
    input_z_scores = np.sum(zC ** 2, axis=0) + zB ** 2
    input_raw_total = float(np.sum(input_raw_scores))
    input_z_total = float(np.sum(input_z_scores))
    for j in range(I):
        top_m_raw = int(np.argmax(dC[:, j] ** 2)) if M > 0 else -1
        top_m_z = int(np.argmax(zC[:, j] ** 2)) if M > 0 else -1
        input_rows.append({
            "layer": layer_name,
            "class_label_a": str(class_a),
            "class_label_b": str(class_b),
            "n_nodes_a": int(len(nodes_a)),
            "n_nodes_b": int(len(nodes_b)),
            "input_index": int(j),
            "input_raw_l2_sq": float(input_raw_scores[j]),
            "input_raw_l2": float(np.sqrt(input_raw_scores[j])),
            "input_raw_contribution_ratio": float(input_raw_scores[j] / (input_raw_total + eps)),
            "input_standardized_l2_sq": float(input_z_scores[j]),
            "input_standardized_l2": float(np.sqrt(input_z_scores[j])),
            "input_standardized_contribution_ratio": float(input_z_scores[j] / (input_z_total + eps)),
            "base_diff": float(dB[j]),
            "base_standardized_diff": float(zB[j]),
            "ef_C_raw_l2_sq": float(np.sum(dC[:, j] ** 2)),
            "ef_C_standardized_l2_sq": float(np.sum(zC[:, j] ** 2)),
            "top_ef_by_raw_input_diff": params.elementary_functions[top_m_raw] if top_m_raw >= 0 else "",
            "top_ef_by_standardized_input_diff": params.elementary_functions[top_m_z] if top_m_z >= 0 else "",
        })

    dim_rows: List[Dict[str, Any]] = []
    # Candidate parameter dimensions. Rank by abs standardized difference; keep
    # top_dims to avoid huge CSVs for wide layers.
    candidates: List[Dict[str, Any]] = []
    for m, fname in enumerate(params.elementary_functions):
        for j in range(I):
            candidates.append({
                "parameter_block": f"{fname}_C",
                "parameter_type": "elementary_C",
                "ef_index": int(m),
                "ef_name": fname,
                "input_index": int(j),
                "mean_a": float(C_mu_a_eff[m, j]),
                "mean_b": float(C_mu_b_eff[m, j]),
                "raw_diff": float(dC[m, j]),
                "standardized_diff": float(zC[m, j]),
            })
        candidates.append({
            "parameter_block": f"{fname}_D",
            "parameter_type": "elementary_D",
            "ef_index": int(m),
            "ef_name": fname,
            "input_index": np.nan,
            "mean_a": float(D_mu_a_eff[m]),
            "mean_b": float(D_mu_b_eff[m]),
            "raw_diff": float(dD[m]),
            "standardized_diff": float(zD[m]),
        })
    for j in range(I):
        candidates.append({
            "parameter_block": "base_weight",
            "parameter_type": "base_weight",
            "ef_index": np.nan,
            "ef_name": "base",
            "input_index": int(j),
            "mean_a": float(B_mu_a[j]),
            "mean_b": float(B_mu_b[j]),
            "raw_diff": float(dB[j]),
            "standardized_diff": float(zB[j]),
        })

    candidates.sort(key=lambda r: abs(r["standardized_diff"]), reverse=True)
    for rank, row in enumerate(candidates[:max(0, int(top_dims))], start=1):
        row = dict(row)
        row.update({
            "layer": layer_name,
            "class_label_a": str(class_a),
            "class_label_b": str(class_b),
            "n_nodes_a": int(len(nodes_a)),
            "n_nodes_b": int(len(nodes_b)),
            "rank_by_abs_standardized_diff": int(rank),
            "abs_raw_diff": float(abs(row["raw_diff"])),
            "abs_standardized_diff": float(abs(row["standardized_diff"])),
        })
        dim_rows.append(row)

    summary = {
        "layer": layer_name,
        "class_label_a": str(class_a),
        "class_label_b": str(class_b),
        "n_nodes_a": int(len(nodes_a)),
        "n_nodes_b": int(len(nodes_b)),
        "include_ef_weight": bool(include_ef_weight),
        "total_raw_l2": float(np.sqrt(total_raw_sq)),
        "total_raw_l2_sq": total_raw_sq,
        "total_standardized_l2": float(np.sqrt(total_z_sq)),
        "total_standardized_l2_sq": total_z_sq,
        "base_raw_contribution_ratio": float(np.sum(dB ** 2) / (total_raw_sq + eps)),
        "ef_raw_contribution_ratio": float((np.sum(dC ** 2) + np.sum(dD ** 2)) / (total_raw_sq + eps)),
        "base_standardized_contribution_ratio": float(np.sum(zB ** 2) / (total_z_sq + eps)),
        "ef_standardized_contribution_ratio": float((np.sum(zC ** 2) + np.sum(zD ** 2)) / (total_z_sq + eps)),
        "top_block_by_raw_ratio": max(block_rows, key=lambda r: r["raw_contribution_ratio"])["block"] if block_rows else "",
        "top_block_raw_ratio": float(max((r["raw_contribution_ratio"] for r in block_rows), default=np.nan)),
        "top_block_by_standardized_ratio": max(block_rows, key=lambda r: r["standardized_contribution_ratio"])["block"] if block_rows else "",
        "top_block_standardized_ratio": float(max((r["standardized_contribution_ratio"] for r in block_rows), default=np.nan)),
        "top_ef_by_raw_total": params.elementary_functions[int(np.argmax(ef_raw_scores))] if M > 0 else "",
        "top_ef_raw_total_ratio": float(np.max(ef_raw_scores) / (ef_raw_total + eps)) if M > 0 else np.nan,
        "top_ef_by_standardized_total": params.elementary_functions[int(np.argmax(ef_z_scores))] if M > 0 else "",
        "top_ef_standardized_total_ratio": float(np.max(ef_z_scores) / (ef_z_total + eps)) if M > 0 else np.nan,
        "top_input_by_raw_difference": int(np.argmax(input_raw_scores)) if I > 0 else -1,
        "top_input_raw_difference_ratio": float(np.max(input_raw_scores) / (input_raw_total + eps)) if I > 0 else np.nan,
        "top_input_by_standardized_difference": int(np.argmax(input_z_scores)) if I > 0 else -1,
        "top_input_standardized_difference_ratio": float(np.max(input_z_scores) / (input_z_total + eps)) if I > 0 else np.nan,
    }

    return block_rows, ef_rows, input_rows, dim_rows, summary


def compute_pairwise_data_difference_tables(
    data_summary_df: pd.DataFrame,
    input_data_df_all: pd.DataFrame,
    ef_data_df_all: pd.DataFrame,
    top_inputs: int = 30,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Compare already-computed data-driven contributions between classes."""
    summary_rows: List[Dict[str, Any]] = []
    input_rows: List[Dict[str, Any]] = []
    ef_rows: List[Dict[str, Any]] = []

    if data_summary_df is not None and len(data_summary_df) > 0:
        value_cols = [
            "base_output_mean_abs",
            "ef_output_mean_abs_sum",
            "ef_to_base_abs_ratio",
            "functional_corr_mean",
        ]
        for layer_name, g in data_summary_df.groupby("layer"):
            labels = sorted(g["class_label"].astype(str).unique())
            by_label = {str(row["class_label"]): row for _, row in g.iterrows()}
            for ia in range(len(labels)):
                for ib in range(ia + 1, len(labels)):
                    a, b = labels[ia], labels[ib]
                    ra, rb = by_label[a], by_label[b]
                    row = {
                        "layer": layer_name,
                        "class_label_a": a,
                        "class_label_b": b,
                        "n_nodes_a": int(ra.get("n_nodes", np.nan)),
                        "n_nodes_b": int(rb.get("n_nodes", np.nan)),
                    }
                    for col in value_cols:
                        if col in data_summary_df.columns:
                            va = float(ra[col]) if pd.notna(ra[col]) else np.nan
                            vb = float(rb[col]) if pd.notna(rb[col]) else np.nan
                            row[f"{col}_a"] = va
                            row[f"{col}_b"] = vb
                            row[f"{col}_diff_a_minus_b"] = float(va - vb) if np.isfinite(va) and np.isfinite(vb) else np.nan
                            row[f"{col}_abs_diff"] = float(abs(va - vb)) if np.isfinite(va) and np.isfinite(vb) else np.nan
                    summary_rows.append(row)

    if input_data_df_all is not None and len(input_data_df_all) > 0:
        value_col = "importance_total_data_weighted"
        if value_col in input_data_df_all.columns:
            for layer_name, g_layer in input_data_df_all.groupby("layer"):
                labels = sorted(g_layer["class_label"].astype(str).unique())
                for ia in range(len(labels)):
                    for ib in range(ia + 1, len(labels)):
                        a, b = labels[ia], labels[ib]
                        ga = g_layer[g_layer["class_label"].astype(str) == a].set_index("input_index")
                        gb = g_layer[g_layer["class_label"].astype(str) == b].set_index("input_index")
                        common = sorted(set(ga.index).intersection(set(gb.index)))
                        pair_rows = []
                        for j in common:
                            va = float(ga.loc[j, value_col])
                            vb = float(gb.loc[j, value_col])
                            pair_rows.append({
                                "layer": layer_name,
                                "class_label_a": a,
                                "class_label_b": b,
                                "input_index": int(j),
                                "importance_total_data_weighted_a": va,
                                "importance_total_data_weighted_b": vb,
                                "data_weighted_input_diff_a_minus_b": float(va - vb),
                                "data_weighted_input_abs_diff": float(abs(va - vb)),
                            })
                        pair_rows.sort(key=lambda r: r["data_weighted_input_abs_diff"], reverse=True)
                        for rank, row in enumerate(pair_rows[:max(0, int(top_inputs))], start=1):
                            row["rank_by_data_weighted_input_abs_diff"] = int(rank)
                            input_rows.append(row)

    if ef_data_df_all is not None and len(ef_data_df_all) > 0:
        value_col = "mean_abs_actual_output"
        if value_col in ef_data_df_all.columns:
            for layer_name, g_layer in ef_data_df_all.groupby("layer"):
                labels = sorted(g_layer["class_label"].astype(str).unique())
                for ia in range(len(labels)):
                    for ib in range(ia + 1, len(labels)):
                        a, b = labels[ia], labels[ib]
                        ga = g_layer[g_layer["class_label"].astype(str) == a].set_index("ef_index")
                        gb = g_layer[g_layer["class_label"].astype(str) == b].set_index("ef_index")
                        common = sorted(set(ga.index).intersection(set(gb.index)))
                        for m in common:
                            va = float(ga.loc[m, value_col])
                            vb = float(gb.loc[m, value_col])
                            ef_name = str(ga.loc[m, "ef_name"]) if "ef_name" in ga.columns else str(m)
                            ef_rows.append({
                                "layer": layer_name,
                                "class_label_a": a,
                                "class_label_b": b,
                                "ef_index": int(m),
                                "ef_name": ef_name,
                                "mean_abs_actual_output_a": va,
                                "mean_abs_actual_output_b": vb,
                                "actual_output_diff_a_minus_b": float(va - vb),
                                "actual_output_abs_diff": float(abs(va - vb)),
                            })

    return pd.DataFrame(summary_rows), pd.DataFrame(input_rows), pd.DataFrame(ef_rows)


