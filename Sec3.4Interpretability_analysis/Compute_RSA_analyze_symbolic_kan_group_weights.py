def write_report_template(path: str, args):
    text = f"""# Same-layer same-class neuron weight analysis

This report summarizes group-level analysis for neurons classified by Neuron-level RSA.

## Parameter vector

For neuron $i$ in layer $l$, the parameter vector is constructed as

$$
\\theta_{{l,i}} = [\\{{\\hat c_{{m,l,i,j}}\\}}_{{m,j}},
\\{{\\hat d_{{l,m,i}}\\}}_m, \\{{w^b_{{l,i,j}}\\}}_j],
$$

where, by default,

$$
\\hat c_{{m,l,i,j}} = s_{{mlp}} c_{{m,l,i,j}},
\\quad
\\hat d_{{l,m,i}} = s_{{mlp}} d_{{l,m,i}}.
$$

The elementary-function prefactor $w_{{l,m}}$ is intentionally omitted when
constructing the parameter vector. Use `--include_ef_weight_in_param_vector`
only if you want to restore the old behavior that multiplies by $w_{{l,m}}$.

The script computes the class centroid, intra-class variance, mean distance to centroid,
pairwise Euclidean distance, and pairwise cosine similarity.

## Parameter-based input importance

For class $\\mathcal C_k$ in layer $l$, the parameter-based input importance is

$$
I^{{param}}_{{l,k,j}} =
\\sum_m |s_{{mlp}} w_{{l,m}}| \\
\\frac{{1}}{{|\\mathcal C_k|}}\\sum_{{i\\in\\mathcal C_k}} |c_{{m,l,i,j}}|
+
\\frac{{1}}{{|\\mathcal C_k|}}\\sum_{{i\\in\\mathcal C_k}} |w^b_{{l,i,j}}|.
$$

Saved in `input_importance_parameter.csv`.

## Data-weighted input importance

If test data are available, the script also computes

$$
I^{{data}}_{{l,k,j}} =
\\sum_m |s_{{mlp}} w_{{l,m}}| \\
\\frac{{1}}{{|\\mathcal C_k|}}\\sum_{{i\\in\\mathcal C_k}} |c_{{m,l,i,j}}|
\\cdot \\mathbb E[|h_{{l-1,j}}|]
+
\\frac{{1}}{{|\\mathcal C_k|}}\\sum_{{i\\in\\mathcal C_k}} |w^b_{{l,i,j}}|
\\cdot \\mathbb E[|b(h_{{l-1,j}})|].
$$

Saved in `input_importance_data.csv`.

## Actual elementary-function contribution

For each elementary function $f_m$, the script estimates

$$
A_{{m,l,k}} = \\frac{{1}}{{|\\mathcal C_k|}}
\\sum_{{i\\in\\mathcal C_k}}
\\mathbb E_{{h_{{l-1}}}}
\\left[
\\left|
s_{{mlp}}w_{{l,m}}f_m\\left(\\sum_j c_{{m,l,i,j}}h_{{l-1,j}} + d_{{l,m,i}}\\right)
\\right|
\\right].
$$

Saved in `ef_data_contribution.csv`.

## Main CSV files

- `class_summary.csv`: class-level consistency and statistics.
- `ef_param_stats.csv`: elementary-function parameter statistics.
- `input_importance_parameter.csv`: parameter-space input importance.
- `input_importance_data.csv`: data-weighted input importance, if enabled.
- `data_contribution_summary.csv`: actual output contribution summary, if enabled.
- `inter_class_distance.csv`: centroid distances between different classes.
- `inter_class_difference_summary.csv`: same-layer class-pair summary explaining which branch/input/function dominates the difference.
- `inter_class_param_block_contribution.csv`: class-pair decomposition into elementary-function C, elementary-function D, and base_weight blocks.
- `inter_class_ef_difference.csv`: class-pair decomposition by elementary function.
- `inter_class_input_difference.csv`: class-pair decomposition by input dimension.
- `inter_class_top_parameter_dimensions.csv`: top individual parameter dimensions ranked by standardized class difference.
- `top*_inter_class_input_difference.csv`: top input dimensions for each same-layer class pair.
- `inter_class_data_contribution_difference.csv`: class-pair differences in actual output contribution, if data analysis is enabled.
- `top*_inter_class_data_input_difference.csv`: class-pair differences in data-weighted input importance, if data analysis is enabled.
- `inter_class_data_ef_difference.csv`: class-pair differences in actual elementary-function output contribution, if data analysis is enabled.
- `class_mean_params/*.npz`: class-wise mean and variance tensors.

## Inter-class difference interpretation

The new inter-class analysis compares every class pair within the same layer.
For two classes $a$ and $b$, it computes the class-mean parameter difference

$$
\\Delta_{a,b} = \\mu_{l,a} - \\mu_{l,b}.
$$

It then decomposes $\\Delta_{a,b}$ into elementary-function $C$ blocks,
elementary-function $D$ bias blocks, base weights, input dimensions, and
individual parameter dimensions. Raw differences indicate where the centroid
distance is large. Standardized differences indicate where the class difference
is large relative to within-class dispersion.

## Important runtime options

- `--scale_param_vector`: {args.scale_param_vector}
- `--include_ef_weight_in_param_vector`: {args.include_ef_weight_in_param_vector}
- `--standardize_vectors`: {args.standardize_vectors}
- `--r_threshold`: {args.r_threshold}
- `--min_group_size`: {args.min_group_size}
"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


