def load_test_inputs_from_loader(args) -> np.ndarray:
    """
    Load test input a_test through your original MyKANnetLoader_2.load_dataset(opt).
    Only the input vector a is needed for contribution analysis.
    """
    try:
        import MyKANnetLoader_2
    except Exception as exc:
        raise ImportError(
            "Cannot import MyKANnetLoader_2. Either run this script in your original "
            "project environment, or use --no_dataset_contribution."
        ) from exc

    train_iter, val_iter, test_iter = MyKANnetLoader_2.load_dataset(args)

    a_list = []
    for batch in test_iter:
        if isinstance(batch, (list, tuple)):
            a = batch[0]
        else:
            a = batch
        a_list.append(a.detach().cpu())

    if len(a_list) == 0:
        raise RuntimeError("test_iter is empty; cannot compute data-driven contribution.")

    a_test = torch.cat(a_list, dim=0).numpy()
    input_dim = parse_int_list(args.layers_hidden)[0]
    a_test = a_test.reshape(-1, input_dim).astype(np.float32)
    return a_test


def sample_inputs(x: np.ndarray, max_samples: int, seed: int = 0) -> np.ndarray:
    if max_samples is None or max_samples <= 0 or x.shape[0] <= max_samples:
        return x
    rng = np.random.default_rng(seed)
    idx = rng.choice(x.shape[0], size=max_samples, replace=False)
    return x[idx]


def collect_layer_inputs_outputs(
    net: SymbolicKAN,
    x_np: np.ndarray,
    device: str,
    forward_batch: int = 512,
) -> Tuple[Dict[str, np.ndarray], Dict[str, np.ndarray]]:
    """
    For each layer l, collect h_{l-1} and h_l on the sampled dataset.
    Returns:
      layer_inputs['Layer1'] = raw input h_0
      layer_outputs['Layer1'] = h_1
      ...
    """
    layer_inputs = {index_to_layer_name(i): [] for i in range(len(net.layers))}
    layer_outputs = {index_to_layer_name(i): [] for i in range(len(net.layers))}

    net.eval()
    with torch.no_grad():
        for start in range(0, x_np.shape[0], forward_batch):
            end = min(start + forward_batch, x_np.shape[0])
            cur = torch.from_numpy(x_np[start:end]).float().to(device)

            for layer_idx, layer in enumerate(net.layers):
                layer_name = index_to_layer_name(layer_idx)
                layer_inputs[layer_name].append(cur.detach().cpu().numpy())
                cur = layer(cur)
                layer_outputs[layer_name].append(cur.detach().cpu().numpy())

    layer_inputs = {k: np.concatenate(v, axis=0) for k, v in layer_inputs.items()}
    layer_outputs = {k: np.concatenate(v, axis=0) for k, v in layer_outputs.items()}
    return layer_inputs, layer_outputs


